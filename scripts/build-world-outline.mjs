// Writes packages/react/src/utils/world-land.ts: the land outline the Globe and DottedMap turn into dots.
//
//   node scripts/build-world-outline.mjs [tolerance-in-degrees]     (default 0.7)
//
// The source is Natural Earth's 1:110m land layer, which is in the public domain (naturalearthdata.com). It is fetched here,
// simplified with the Douglas-Peucker method and written as plain numbers, so nothing is downloaded when the library runs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const url = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";
const tolerance = Number(process.argv[2] ?? 0.7);
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../packages/react/src/utils/world-land.ts");

const data = await (await fetch(url)).json();

function simplify(points, tol) {
  if (points.length <= 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let worst = -1;
    let at = -1;
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const len = Math.hypot(bx - ax, by - ay) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((by - ay) * points[i][0] - (bx - ax) * points[i][1] + bx * ay - by * ax) / len;
      if (d > worst) {
        worst = d;
        at = i;
      }
    }
    if (worst > tol) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

// A ring starts and ends at the same point, so it is cut at the point farthest from its start and each half is simplified.
function simplifyRing(ring, tol) {
  let far = 0;
  let best = -1;
  for (let i = 1; i < ring.length - 1; i++) {
    const d = Math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1]);
    if (d > best) {
      best = d;
      far = i;
    }
  }
  if (far === 0) return ring;
  const a = simplify(ring.slice(0, far + 1), tol);
  const b = simplify(ring.slice(far), tol);
  return [...a, ...b.slice(1)];
}

const polygons = [];
for (const f of data.features) {
  const g = f.geometry;
  const list = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of list) {
    const rings = poly
      .map((ring) => simplifyRing(ring, tolerance).map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]))
      .filter((ring) => ring.length >= 4);
    if (rings.length) polygons.push(rings);
  }
}

const body = polygons.map((rings) => `  [${rings.map((r) => `[${r.map(([x, y]) => `[${x},${y}]`).join(",")}]`).join(",")}],`).join("\n");
fs.writeFileSync(
  out,
  `// Generated by scripts/build-world-outline.mjs from Natural Earth (public domain) 1:110m land, simplified to ${tolerance} degrees.\n// Each polygon is an outer ring followed by any holes, as [longitude, latitude] pairs. Do not edit by hand.\n\nexport type Ring = ReadonlyArray<readonly [number, number]>;\n\nexport const WORLD_LAND: ReadonlyArray<ReadonlyArray<Ring>> = [\n${body}\n];\n`,
);
console.log(`${polygons.length} polygons, ${polygons.reduce((n, p) => n + p.reduce((m, r) => m + r.length, 0), 0)} points -> ${out}`);
